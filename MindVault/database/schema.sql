CREATE DATABASE IF NOT EXISTS mindvault;
USE mindvault;
CREATE TABLE IF NOT EXISTS notes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(150) NOT NULL,
 category VARCHAR(60) NOT NULL DEFAULT 'General', content TEXT NOT NULL,
 pinned BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 next_review DATE NULL, review_count INT NOT NULL DEFAULT 0,
 INDEX(title), INDEX(next_review));
CREATE TABLE IF NOT EXISTS tags(id BIGINT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(40) UNIQUE NOT NULL);
CREATE TABLE IF NOT EXISTS note_tags(note_id BIGINT,tag_id BIGINT,PRIMARY KEY(note_id,tag_id),
 FOREIGN KEY(note_id) REFERENCES notes(id) ON DELETE CASCADE,
 FOREIGN KEY(tag_id) REFERENCES tags(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS note_links(note_id BIGINT,linked_note_id BIGINT,PRIMARY KEY(note_id,linked_note_id),
 FOREIGN KEY(note_id) REFERENCES notes(id) ON DELETE CASCADE,
 FOREIGN KEY(linked_note_id) REFERENCES notes(id) ON DELETE CASCADE,CHECK(note_id<>linked_note_id));
CREATE TABLE IF NOT EXISTS tasks(id BIGINT PRIMARY KEY AUTO_INCREMENT,title VARCHAR(180) NOT NULL,
 due_date DATE NULL,priority ENUM('LOW','MEDIUM','HIGH') DEFAULT 'MEDIUM',
 status ENUM('PENDING','DONE') DEFAULT 'PENDING',notified BOOLEAN DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,INDEX(status,due_date,notified));
